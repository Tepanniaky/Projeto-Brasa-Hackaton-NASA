/** Metodologia, fontes, qualidade e limitações, construídos a partir dos manifestos (nada fixo no código). */
import type { Dataset } from '../data/types';
import { fmt1, fmtHour, fmtInt, fmtPct } from '../domain/format';
import { dataText, flagText } from '../i18n/dataText';
import { tr } from '../i18n/lang';

const DROP_LABEL: Record<string, [string, string]> = {
  satelite_fora_do_escopo: ['satélite fora do escopo', 'satellite out of scope'],
  duplicado: ['duplicado', 'duplicate'],
  tipo_nao_vegetacao: ['tipo ≠ 0 (fonte estática, vulcão, mar)', 'type ≠ 0 (static source, volcano, offshore)'],
  baixa_confianca: ['baixa confiança', 'low confidence'],
  fora_da_regiao: ['fora da Bahia', 'outside Bahia'],
  fora_do_periodo: ['fora do período', 'outside the period'],
};
const dropLabel = (k: string) => (DROP_LABEL[k] ? tr(...DROP_LABEL[k]) : k);

export function MethodPanel({ ds }: { ds: Dataset }) {
  const s = ds.sensors;
  const harm = s?.harmonization;
  const and = tr(' e ', ' and ');
  return (
    <section className="secao" aria-labelledby="sec-metodo" id="metodologia" data-testid="metodologia">
      <span className="rotulo-secao">{tr('4 · Método e limites', '4 · Method and limits')}</span>
      <h2 id="sec-metodo">{tr('Como ler estes dados', 'How to read these data')}</h2>
      <p className="secao-sub">{tr('Tudo abaixo é lido dos manifestos gerados pelo pipeline. O documento completo está em', 'Everything below is read from the manifests generated by the pipeline. The full document is in')} <code>docs/METHODOLOGY.md</code>{tr('.', ' (Portuguese).')}</p>

      <details className="metodo" open>
        <summary>{tr('Limitações que mudam a leitura', 'Limitations that change the reading')}</summary>
        <ul>
          <li>{tr('Uma detecção é um pixel com fogo ativo no instante da passagem do satélite. Não é um incêndio, e focos não são convertidos em área queimada.',
                  'A detection is a pixel with active fire at the moment the satellite passes over. It is not a wildfire, and detections are not converted into burned area.')}</li>
          <li>{tr('Ausência de detecção não comprova ausência de fogo. Nuvens, fumaça, copa das árvores, fogo pequeno ou fora do horário da passagem escapam ao sensor. Os arquivos de focos não trazem a cobertura de nuvens.',
                  'No detection does not prove no fire. Clouds, smoke, tree canopy, small fires or fires outside the overpass time escape the sensor. The fire files do not include cloud cover.')}</li>
          <li>{tr('MODIS e VIIRS nunca são somados. O VIIRS (pixel de 375 m) detecta focos menores que o MODIS (1 km). Contar os dois juntos duplicaria fogo e misturaria escalas.',
                  'MODIS and VIIRS are never added together. VIIRS (375 m pixel) detects smaller fires than MODIS (1 km). Counting both together would double-count fire and mix scales.')}</li>
          <li>{tr('As escalas de confiança não são equivalentes: MODIS usa 0–100 %, VIIRS usa as classes baixa, nominal e alta.',
                  'The confidence scales are not equivalent: MODIS uses 0–100%, VIIRS uses the classes low, nominal and high.')}</li>
          <li>{tr('A harmonização é uma aproximação estatística entre escalas de detecção. Ela não mede a quantidade real de fogo.',
                  'Harmonization is a statistical approximation between detection scales. It does not measure the actual amount of fire.')}</li>
          <li>{tr('Ano corrente: dados preliminares (processamento rápido, NRT). Semanas ainda não publicadas aparecem como "sem dado", não como "sem fogo".',
                  'Current year: preliminary data (near real-time processing, NRT). Weeks not yet published appear as "no data", not as "no fire".')}</li>
        </ul>
      </details>

      <details className="metodo">
        <summary>{tr('Duas camadas de dados', 'Two data layers')}</summary>
        <ul>
          <li>{tr(<><strong>Série da equipe</strong> (calendário semanal 2003–hoje): MODIS Terra+Aqua observado até 2021, VIIRS (S-NPP, NOAA-20 e NOAA-21) convertido a partir de 2022. Os scripts que a geraram não estão neste repositório. A validação de "erro médio de 2,2 % no total anual" informada pela equipe <strong>não foi reproduzida</strong> aqui.</>,
                  <><strong>Team series</strong> (weekly calendar 2003–present): observed MODIS Terra+Aqua through 2021, VIIRS (S-NPP, NOAA-20 and NOAA-21) converted from 2022 on. The scripts that produced it are not in this repository. The team&apos;s reported validation of a &quot;2.2% mean error in the annual total&quot; <strong>was not reproduced</strong> here.</>)}</li>
          {s?.audit && <li>{tr(`Auditoria independente: a série da equipe de 2020–2021 foi reproduzida exatamente em ${s.audit.municipios_reproduzidos_2020_2021} de ${s.audit.municipios_auditados} municípios. Método: `,
                               `Independent audit: the team series for 2020–2021 was exactly reproduced in ${s.audit.municipios_reproduzidos_2020_2021} of ${s.audit.municipios_auditados} municipalities. Method: `)}{dataText(s.audit.metodo)}</li>}
          <li>{tr(<><strong>Registros por sensor</strong> (BRASA, mensal 2020–2025): MODIS/Aqua e VIIRS/NOAA-20, com critérios de qualidade próprios de cada produto, gerados pelo pipeline Python deste repositório.</>,
                  <><strong>Records by sensor</strong> (BRASA, monthly 2020–2025): MODIS/Aqua and VIIRS/NOAA-20, each with its own product-specific quality criteria, generated by this repository&apos;s Python pipeline.</>)}</li>
        </ul>
      </details>

      {s && (
        <>
          <details className="metodo">
            <summary>{tr('Definição de dia, horário e grade', 'Definition of day, time and grid')}</summary>
            <ul>
              <li>{dataText(s.manifest.definicao_dia)}</li>
              <li>{tr('A série da equipe usa outra convenção: semana = bloco fixo de 7 dias desde 1º de janeiro, pela data UTC; a semana 51 absorve os últimos dias do ano.',
                      'The team series uses a different convention: week = fixed 7-day block from January 1, by UTC date; week 51 absorbs the last days of the year.')}</li>
              <li>{tr('Grades comuns de', 'Common grids of')} {s.manifest.grades.map((g) => `${g.tamanho_m / 1000} km (${fmtInt(g.fragmentos)} ${tr('fragmentos', 'fragments')})`).join(and)} {tr('em', 'in')} {s.manifest.grades[0]?.crs} {tr('(SIRGAS 2000 / Brazil Albers, de área igual). Fragmento = célula ∩ município. Os valores dos municípios somam o estado.',
                     '(SIRGAS 2000 / Brazil Albers, equal-area). Fragment = cell ∩ municipality. Municipal values add up to the state.')}</li>
              <li>{tr('Município de cada detecção: ponto-no-polígono com a malha do IBGE', 'Municipality of each detection: point-in-polygon with the IBGE boundaries')} ({dataText(String(s.manifest.atribuicao_municipio.predicado))}).</li>
            </ul>
          </details>

          <details className="metodo">
            <summary>{tr('Sensores e critérios de qualidade', 'Sensors and quality criteria')}</summary>
            <ul>
              {s.manifest.sensores.map((x) => (
                <li key={x.id}><strong>{x.rotulo}</strong>: {x.produto}; {tr('pixel nominal', 'nominal pixel')} {fmtInt(x.pixel_nominal_m)} m. {tr('Regra', 'Rule')}: {dataText(x.regra_qualidade)}.</li>
              ))}
            </ul>
            <div className="tabela-wrap">
              <table className="dados" data-testid="tabela-qualidade">
                <thead><tr><th>Sensor</th><th>{tr('Ano', 'Year')}</th><th>{tr('Linhas no recorte', 'Rows in subset')}</th><th>{tr('Mantidas', 'Kept')}</th>
                  <th>{tr('Descartes', 'Dropped')}</th><th>{tr('Versão', 'Version')}</th><th>{tr('Processamento', 'Processing')}</th></tr></thead>
                <tbody>{s.manifest.qualidade.filter((q) => !q.sensor.includes('Terra')).map((q) => (
                  <tr key={`${q.sensor}${q.ano}`}><td>{q.sensor}</td><td>{q.ano}</td><td>{fmtInt(q.linhas)}</td><td>{fmtInt(q.mantidos)}</td>
                    <td style={{ textAlign: 'left', whiteSpace: 'normal' }}>{Object.entries(q.descartes).map(([k, v]) => `${dropLabel(k)}: ${fmtInt(v)}`).join('; ')}</td>
                    <td>{q.versoes.join(', ')}</td><td>{q.processamento.join(', ')}</td></tr>
                ))}</tbody>
              </table>
            </div>
            <p className="nota">{tr('Versão MODIS "6.03" = Collection 6 e "61.03" = Collection 6.1 (convenção CCC.VV do MCD14ML). A troca acontece entre 2022 e 2023, na mesma fronteira entre os anos de ajuste e de avaliação.',
                                    'MODIS version "6.03" = Collection 6 and "61.03" = Collection 6.1 (MCD14ML CCC.VV convention). The switch happens between 2022 and 2023, on the same boundary as between the fitting and evaluation years.')}</p>
          </details>

          <details className="metodo">
            <summary>{tr('Indisponibilidades e deriva orbital', 'Outages and orbital drift')}</summary>
            <ul>
              {s.manifest.indisponibilidades.map((g) => (
                <li key={g.start}><strong>{g.sensor}</strong> {tr('de', 'from')} {g.start} {tr('a', 'to')} {g.end} ({dataText(g.kind)}): {dataText(g.note)} {tr('Fonte', 'Source')}: {g.source}.</li>
              ))}
            </ul>
            <div className="tabela-wrap">
              <table className="dados">
                <thead><tr><th>{tr('Satélite', 'Satellite')}</th>{[...new Set(s.manifest.deriva_passagem.map((d) => d.ano))].sort().map((y) => <th key={y}>{y}</th>)}</tr></thead>
                <tbody>{['Aqua', 'N20', 'Terra'].map((sat) => (
                  <tr key={sat}><td>{sat === 'N20' ? 'NOAA-20' : sat}</td>
                    {s.manifest.deriva_passagem.filter((d) => d.satelite === sat).sort((a, b) => a.ano - b.ano)
                      .map((d) => <td key={d.ano}>{fmtHour(d.hora_local_mediana)}</td>)}</tr>
                ))}</tbody>
              </table>
            </div>
            <p className="nota">{tr('Horário local mediano das detecções diurnas, medido nos próprios dados. Uma mudança de horário altera quanto do ciclo diário do fogo o sensor enxerga.',
                                    'Median local time of daytime detections, measured in the data themselves. A change in overpass time changes how much of the daily fire cycle the sensor sees.')}</p>
          </details>

          {harm && (
            <details className="metodo" data-testid="avaliacao-harmonizacao">
              <summary>{tr('Harmonização experimental e avaliação', 'Experimental harmonization and evaluation')}</summary>
              <ul>
                <li>{tr('Referência', 'Reference')}: <strong>{harm.referencia}</strong>; {tr('preditor', 'predictor')}: {harm.preditor}; {tr('unidade', 'unit')}: {dataText(harm.unidade)}.</li>
                <li>{tr(`Ajuste com ${harm.anos_ajuste.join(', ')} (sem ${harm.meses_excluidos_do_ajuste.join(' e ')}, falha do Aqua); avaliação em ${harm.anos_avaliacao.join(', ')}, anos nunca vistos pelo ajuste.`,
                        `Fitted on ${harm.anos_ajuste.join(', ')} (excluding ${harm.meses_excluidos_do_ajuste.join(' and ')}, Aqua outage); evaluated on ${harm.anos_avaliacao.join(', ')}, years never seen by the fit.`)}</li>
                <li>{tr('Métodos: sem ajuste, razão simples e binomial negativa (log μ = log área + β·log(1+VIIRS) + mês).',
                        'Methods: no adjustment, simple ratio and negative binomial (log μ = log area + β·log(1+VIIRS) + month).')} {dataText(harm.intervalo)}.</li>
                <li>{tr(`Grade usada na interface: ${harm.grade_padrao === 'g10' ? '10 km' : '5 km'}, escolhida por regra fixa: menor erro relativo nos anos de avaliação.`,
                        `Grid used in the interface: ${harm.grade_padrao === 'g10' ? '10 km' : '5 km'}, chosen by a fixed rule: lowest relative error in the evaluation years.`)}</li>
                <li>{dataText(harm.aviso)}</li>
              </ul>
              {(['g10', 'g5'] as const).map((gid) => {
                const g = harm.grades[gid];
                if (!g) return null;
                const rows = g.avaliacao.metricas.filter((m) => m.nivel === 'estado_mes');
                const years = [...new Set(rows.map((r) => r.ano))].sort();
                const cov = g.avaliacao.cobertura.filter((c) => c.nivel === 'estado_mes');
                return (
                  <div key={gid}>
                    <h3>{tr(`Grade de ${g.tamanho_m / 1000} km: erro absoluto médio mensal do estado`, `${g.tamanho_m / 1000} km grid: mean absolute error of the state monthly total`)}</h3>
                    <div className="tabela-wrap">
                      <table className="dados">
                        <thead><tr><th>{tr('Ano', 'Year')}</th><th>{tr('Divisão', 'Split')}</th><th>{tr('Sem ajuste', 'No adjustment')}</th><th>{tr('Razão simples', 'Simple ratio')}</th>
                          <th>{tr('Binomial negativa', 'Negative binomial')}</th><th>{tr('Cobertura do IC 90 %', '90% CI coverage')}</th></tr></thead>
                        <tbody>{years.map((y) => {
                          const by = Object.fromEntries(rows.filter((r) => r.ano === y).map((r) => [r.metodo, r]));
                          const best = by.binomial_negativa && by.razao && by.sem_ajuste && by.binomial_negativa.mae < Math.min(by.razao.mae, by.sem_ajuste.mae);
                          const c = cov.find((x) => x.ano === y);
                          return (
                            <tr key={y} className={by.binomial_negativa?.divisao === 'avaliacao' && !best ? 'marcado' : ''}>
                              <td>{y}</td><td>{dataText(by.binomial_negativa?.divisao)}</td>
                              <td>{by.sem_ajuste ? fmt1(by.sem_ajuste.mae) : '—'}</td><td>{by.razao ? fmt1(by.razao.mae) : '—'}</td>
                              <td>{by.binomial_negativa ? `${fmt1(by.binomial_negativa.mae)}${best ? ' ✓' : ''}` : '—'}</td>
                              <td>{c ? fmtPct(c.cobertura_observada) : '—'}</td>
                            </tr>
                          );
                        })}</tbody>
                      </table>
                    </div>
                    {g.ajuste.binomial_negativa && (
                      <p className="nota">β(log1p VIIRS) = {fmt1(g.ajuste.binomial_negativa.params.log1p_viirs)}; α = {g.ajuste.binomial_negativa.alpha.toFixed(2)}; {tr('dispersão de Pearson do Poisson', 'Poisson Pearson dispersion')} = {g.ajuste.binomial_negativa.dispersao_pearson_poisson.toFixed(2)}; Ljung-Box ({tr('resíduos mensais do treino', 'monthly training residuals')}) p = {g.diagnosticos.ljung_box_p?.toFixed(3)}. {tr('Linhas marcadas: anos de avaliação em que o modelo não superou a melhor linha de base.', 'Highlighted rows: evaluation years in which the model did not beat the best baseline.')}</p>
                    )}
                    <ul>{g.avaliacao.marcacoes.filter((f) => f.nivel !== 'municipio_mes').map((f) => <li key={f.mensagem}>⚠ {flagText(f)}</li>)}</ul>
                  </div>
                );
              })}
              <h3>{tr('Em qual unidade os sensores ficam mais próximos?', 'In which unit are the sensors closest?')}</h3>
              <div className="tabela-wrap">
                <table className="dados">
                  <thead><tr><th>{tr('Métrica', 'Metric')}</th>{Object.keys(harm.comparabilidade[0]?.razao_viirs_modis_por_ano ?? {}).map((y) => <th key={y}>{y}</th>)}<th>{tr('CV da razão', 'Ratio CV')}</th><th>{tr('Spearman mês', 'Monthly Spearman')}</th></tr></thead>
                  <tbody>{harm.comparabilidade.map((c) => (
                    <tr key={c.metrica}><td>{dataText(s.manifest.metricas.find((m) => m.id === c.metrica)?.rotulo)}</td>
                      {Object.values(c.razao_viirs_modis_por_ano).map((v, i) => <td key={i}>{v === null ? '—' : `${fmt1(v)}×`}</td>)}
                      <td>{c.cv_razao_anual === null ? '—' : c.cv_razao_anual.toFixed(3)}</td><td>{c.spearman_estado_mes.toFixed(2)}</td></tr>
                  ))}</tbody>
                </table>
              </div>
              <p className="nota">{tr('Razão VIIRS ÷ MODIS no total anual do estado. Um coeficiente de variação (CV) menor indica uma relação mais estável entre os anos.',
                                      'VIIRS ÷ MODIS ratio of the state annual total. A lower coefficient of variation (CV) means a more stable relationship across years.')}</p>
            </details>
          )}

          <details className="metodo">
            <summary>{tr('Fontes e procedência', 'Sources and provenance')}</summary>
            <ul>
              {s.manifest.fontes_firms.map((f) => (
                <li key={`${f.product}${f.year}`}>{f.product} {f.year}: <a href={f.source_url ?? '#'}>{f.source_url}</a>; {tr(`${fmtInt(f.source_rows)} linhas no arquivo nacional, ${fmtInt(f.subset_rows)} no recorte.`, `${fmtInt(f.source_rows)} rows in the national file, ${fmtInt(f.subset_rows)} in the subset.`)} SHA-256 {f.sha256_verified ? tr('conferido com o servidor', 'verified against the server') : tr('NÃO conferido', 'NOT verified')}: <span className="hash">{f.source_sha256.slice(0, 16)}…</span></li>
              ))}
              <li>{tr('Malha municipal IBGE', 'IBGE municipal boundaries')} ({s.manifest.fontes_ibge.crs}): <span className="hash">{s.manifest.fontes_ibge.sha256.slice(0, 16)}…</span></li>
              <li>Pipeline {s.manifest.pipeline_version}, {tr('gerado em', 'generated at')} {s.manifest.gerado_em_utc} (UTC). {tr('Tipo de dado', 'Data type')}: {s.manifest.dataset_kind}.</li>
              <li>{tr('Mapa de fundo: OpenFreeMap, com dados © OpenStreetMap e OpenMapTiles.', 'Basemap: OpenFreeMap, with data © OpenStreetMap and OpenMapTiles.')}</li>
            </ul>
          </details>
        </>
      )}
    </section>
  );
}
